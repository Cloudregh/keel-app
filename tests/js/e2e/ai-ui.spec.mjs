// Phase 5: the Daily coach's UI (claude.ai only). The model is replaced by a scripted mock, so no AI call is made.
import { test, expect } from "../fixtures/keel.mjs";

// Installs a scripted `sample` before the app boots. mode: stream | long | html | rate_limited | not_granted | error | slow
async function withCoach(page, mode) {
  await page.addInitScript(mode => {
    let calls = 0;
    const sample = (prompt, opts = {}) => new Promise((resolve, reject) => {
      calls++; window.__coachCalls = calls;
      const fail = (code, message) => reject({ code, message });
      if (mode === "rate_limited") return fail("rate_limited", "slow down");
      if (mode === "not_granted") return fail("not_granted", "no");
      if (mode === "error" && calls === 1) return fail("unavailable", "x");
      const text = mode === "long" ? ("A very long coaching paragraph without breaks " + "x".repeat(4000) + " ").repeat(3)
        : mode === "html" ? '<img src=x onerror="window.__xss=1"><b>bold</b> **markdown** and <script>window.__xss=2</script> text'
        : "You focused for 2h. Breaks were regular. Tomorrow, start with the proposal.";
      // Long mode streams the same text in 400-character pieces: at 20 characters every 15 ms it took 9 s or more
      // before the overflow checks even ran, and timed out on a loaded Mac (Phase 14, 2026-11-15). Text and checks unchanged.
      const parts = text.match(mode === "long" ? /.{1,400}/gs : /.{1,20}/gs) || [text];
      let i = 0, acc = "";
      const step = () => {
        if (opts.signal && opts.signal.aborted) return fail("aborted", "stopped");
        if (i < parts.length) { acc += parts[i++]; if (opts.onText) opts.onText({ text: acc, delta: parts[i - 1] }); setTimeout(step, mode === "slow" ? 200 : 15); }
        else resolve({ text: acc, truncated: false });
      };
      if (opts.signal) opts.signal.addEventListener("abort", () => fail("aborted", "stopped"));
      step();
    });
    window.claude = { use: async n => (n === "sample" ? sample : null) };
  }, mode);
  await page.clock.setFixedTime(new Date("2026-11-10T18:00:00Z"));
  await page.reload();
  await page.locator('#nav [data-view="today"]').click();
}
const run = page => page.locator('#ai-panel [data-act="ai"]').click();

test("streams the answer as it arrives, then re-enables the button", async ({ keel: { page } }) => {
  await withCoach(page, "slow");
  await run(page);
  await expect(page.locator('#ai-panel [data-act="ai"]')).toBeDisabled();
  await expect(page.locator("#ai-out")).not.toHaveText("Thinking…");
  const partial = await page.locator("#ai-out").innerText();
  await expect(page.locator("#ai-out")).toHaveText("You focused for 2h. Breaks were regular. Tomorrow, start with the proposal.", { timeout: 10_000 });
  expect(partial.length).toBeLessThan(76);
  await expect(page.locator('#ai-panel [data-act="ai"]')).toBeEnabled();
});

test("AI-generated text is labelled as such", async ({ keel: { page } }) => {
  await withCoach(page, "stream");
  await run(page);
  await expect(page.locator("#ai-out")).toContainText("Tomorrow");
  await expect(page.locator("#ai-panel")).toContainText(/AI-generated|Generated by AI|Written by AI/);
});

test("the user can stop a generation in progress", async ({ keel: { page } }) => {
  await withCoach(page, "slow");
  await run(page);
  const stop = page.locator('#ai-panel [data-act="ai-stop"]');
  await expect(stop).toBeVisible();
  await stop.click();
  await expect(page.locator("#ai-out")).toContainText(/Stopped/);
  await expect(page.locator('#ai-panel [data-act="ai"]')).toBeEnabled();
});

test("a failed generation can be retried", async ({ keel: { page } }) => {
  await withCoach(page, "error");
  await run(page);
  await expect(page.locator("#ai-out")).toContainText("couldn't be generated");
  await run(page);
  await expect(page.locator("#ai-out")).toContainText("Tomorrow");
});

test("rate limit shows a clear message; no permission hides the coach", async ({ keel: { page } }) => {
  await withCoach(page, "rate_limited");
  await run(page);
  await expect(page.locator("#ai-out")).toContainText("busy right now");
  await withCoach(page, "not_granted");
  await run(page);
  await expect(page.locator("#ai-panel")).toBeHidden();
});

test("very long output stays inside the panel (no horizontal overflow)", async ({ keel: { page } }) => {
  await withCoach(page, "long");
  await run(page);
  await expect(page.locator('#ai-panel [data-act="ai"]')).toBeEnabled({ timeout: 20_000 });
  const m = await page.evaluate(() => { const p = document.querySelector("#ai-panel"), o = document.querySelector("#ai-out"); return { panel: p.getBoundingClientRect().right, out: o.getBoundingClientRect().right, scroll: document.documentElement.scrollWidth, vw: innerWidth }; });
  expect(m.out).toBeLessThanOrEqual(m.panel + 1);
  expect(m.scroll).toBeLessThanOrEqual(m.vw);
});

test("HTML or markdown in AI output is shown as text, never executed", async ({ keel: { page } }) => {
  await withCoach(page, "html");
  await run(page);
  await expect(page.locator('#ai-panel [data-act="ai"]')).toBeEnabled();
  await expect(page.locator("#ai-out")).toContainText("<img src=x");
  expect(await page.locator("#ai-out img, #ai-out script, #ai-out b").count()).toBe(0);
  expect(await page.evaluate(() => window.__xss)).toBeUndefined();
});

test.describe("bug 27: reviews are rate-limited per user", () => {
  const ANSWER = "You focused for 2h. Breaks were regular. Tomorrow, start with the proposal.";
  test("one a minute after a finished answer", async ({ keel: { page } }) => {
    await withCoach(page, "stream");
    await run(page);
    await expect(page.locator("#ai-out")).toHaveText(ANSWER);
    await run(page);                                              // straight away: refused without calling the model
    await expect(page.locator("#ai-panel")).toContainText("You can ask for another review in 60 seconds");
    await expect(page.locator("#ai-out")).toHaveText(ANSWER);     // the last answer stays readable
    expect(await page.evaluate(() => window.__coachCalls)).toBe(1);
    await page.clock.setFixedTime(new Date("2026-11-10T18:01:01Z"));
    await run(page);
    await expect(page.locator("#ai-out")).toHaveText(ANSWER);
    expect(await page.evaluate(() => window.__coachCalls)).toBe(2);
  });
  test("at most 20 a day; the count resets the next day", async ({ keel: { page } }) => {
    await withCoach(page, "stream");
    await page.evaluate(() => localStorage.setItem("keel.ai.v1", JSON.stringify({ day: "2026-11-10", count: 20, last: 0 })));
    await run(page);
    await expect(page.locator("#ai-out")).toHaveText("You've had 20 reviews today, the daily limit. The next one is available tomorrow.");
    expect(await page.evaluate(() => window.__coachCalls ?? 0)).toBe(0);
    await page.clock.setFixedTime(new Date("2026-11-11T09:00:00Z"));
    await run(page);
    await expect(page.locator("#ai-out")).toHaveText(ANSWER);
    expect(await page.evaluate(() => window.__coachCalls)).toBe(1);
  });
  test("a failed answer doesn't make you wait, but counts toward the day", async ({ keel: { page } }) => {
    await withCoach(page, "error");
    await run(page);
    await expect(page.locator("#ai-out")).toContainText("couldn't be generated");
    await run(page);
    await expect(page.locator("#ai-out")).toHaveText(ANSWER);
    expect(await page.evaluate(() => JSON.parse(localStorage.getItem("keel.ai.v1")).count)).toBe(2);
  });
});
